/** Site-relative URL of the generated manifest; also its key inside each pack cache. */
export const OFFLINE_PACK_MANIFEST_URL = "/offline-packs/manifest.json";

/** Bumped whenever this manifest's on-disk shape changes (not its content). */
export const OFFLINE_PACK_SCHEMA_VERSION = 1;

/**
 * Bumped whenever a *required* generated resource changes (new/edited words,
 * a grammar deck edit, a new audio file). A plain, hand-maintained string
 * (not a content hash) so a diff of this file is the changelog, matching the
 * plan's maintenance note: "Subir contentVersion cuando cambie un recurso
 * requerido." `scripts/offline-packs/generate.mjs` stamps every generated
 * file and the manifest with this same value so `validate.mjs` can catch a
 * stale/partial regeneration.
 */
export const OFFLINE_PACK_CONTENT_VERSION = "v1";

