/**
 * Discriminated-union types for a CEFR "resource pack" — the bundle a learner
 * can download once (Essential Words + grammar decks + their audio + an
 * optional Coach content-bank slice) to study a whole level offline.
 *
 * Step 1 (Plan 057) only defines these types and generates the Essential
 * Words resource files + manifest. `resource-pack-manager.ts` (Step 3) reads
 * this manifest at download time; nothing here talks to CacheStorage or
 * Dexie yet.
 *
 * Registry-style discriminated union on `kind`, per ENGINEERING_STANDARDS.md
 * ("Many variants → registry + type guard, not long if/switch chains").
 */

